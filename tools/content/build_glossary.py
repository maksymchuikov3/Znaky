"""Будує «Словник водія» (книга з 7 розділів) у feature/car/.../GlossaryTerms.kt і terms.json.

Запуск: python3 tools/content/build_glossary.py [шлях_до_terms.json]
"""
import json, re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from glossary_pdr import PDR_OFFICIAL, PDR_OTHER
from glossary_more import ELECTRIC, MOTO, WATER
from glossary_car import BODY, ENGINE, TRANSMISSION, CHASSIS, BRAKES, SAFETY, ELECTRICS, SPECS, SERVICE

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "feature/car/src/main/kotlin/com/znaky/feature/car/GlossaryTerms.kt"

CHAPTERS = [
    ("PDR", "Терміни Правил", "Усі терміни з пункту 1.10 Правил дорожнього руху, переказані простими словами.", "ПДР п. 1.10", PDR_OFFICIAL),
    ("RULES", "Поняття з інших розділів ПДР", "Слова, які трапляються в Правилах та на іспиті, хоч і не мають окремого визначення в п. 1.10.", "ПДР", PDR_OTHER),
    ("BODY", "Кузов і типи кузовів", "Геометрія авто, силові елементи кузова і чим седан відрізняється від ліфтбека.", "Будова авто", BODY),
    ("ENGINE", "Двигун, паливо й вихлоп", "Як працює двигун, наддув, впорскування, охолодження і системи очищення вихлопу.", "Будова авто", ENGINE),
    ("TRANSMISSION", "Трансмісія і привід", "Зчеплення, коробки передач, диференціали і види приводу.", "Будова авто", TRANSMISSION),
    ("CHASSIS", "Ходова, колеса й гальма", "Підвіска, кермо, шини, диски і гальмівна система.", "Будова авто", CHASSIS + BRAKES),
    ("SAFETY", "Безпека і системи допомоги", "Безпечне водіння, пасивна безпека, електронні помічники водія і домедична допомога.", "Безпека руху", SAFETY),
    ("ELECTRICS", "Електрика й діагностика", "Акумулятор, світло, блоки керування і що означають помилки на панелі.", "Будова авто", ELECTRICS),
    ("ELECTRIC", "Електромобілі та гібриди", "Гібриди, батарея, зарядка, роз'єми та особливості електроавто.", "Електромобіль", ELECTRIC),
    ("SERVICE", "Характеристики, ТО і купівля", "Цифри з техпаспорта, бездоріжжя, обслуговування, перевірка вживаного авто і трохи гаражного сленгу.", "Експлуатація авто", SPECS + SERVICE),
    ("MOTO", "Мотоцикл", "Будова мотоцикла, екіпірування і правила для категорій A1 та A.", "Мотоцикл", MOTO),
    ("WATER", "Мале судно", "Човни, гідроцикли й правила плавання для судноводія.", "Мале судно", WATER),
]

def kstr(s):
    return "null" if s is None else '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

seen = set()
rows, js = [], []
for cid, title, intro, default_src, items in CHAPTERS:
    for term, text, see, syn in items:
        key = (term, cid)
        assert key not in seen, key
        seen.add(key)
        assert text.endswith((".", "»", ")")), term
        src = default_src if cid != "PDR" else "ПДР п. 1.10"
        rows.append(f"    GlossaryTerm({kstr(term)}, TermCategory.{cid}, {kstr(text)}, {kstr(src)}, {kstr(see)}, {kstr(syn)}),")
        js.append({"term": term, "chapter": cid, "chapterTitle": title, "text": text, "source": src, "see": see, "synonyms": syn})

chapters_kt = "\n".join(
    f"    {cid}({kstr(title)}, {kstr(intro)}, {i + 1}),"
    for i, (cid, title, intro, _, _) in enumerate(CHAPTERS)
)

OUT.write_text(f"""package com.znaky.feature.car

// Generated by tools/content/build_glossary.py — edit the data there, not here.
// Chapter 1 retells every term of ПДР п. 1.10 in plain words; the official wording is in the Rules.

/** Chapters of the «Словник водія» book, in reading order. */
internal enum class TermCategory(val title: String, val intro: String, val number: Int) {{
{chapters_kt}
}}

internal val GlossaryTerms: List<GlossaryTerm> = listOf(
{chr(10).join(rows)}
)
""")
print(len(rows), "terms;", {c[0]: len(c[4]) for c in CHAPTERS})
if len(sys.argv) > 1:
    pathlib.Path(sys.argv[1]).write_text(json.dumps(js, ensure_ascii=False, indent=1))
